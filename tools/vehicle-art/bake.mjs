// Offline authoring only; the shipped renderer never loads the simplifier.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import * as T from '../../packages/render-effects/three.js';
import {VEHICLE_BODIES} from '../../packages/vehicle-visuals/catalogue.js';
import {sculptRoadVehicle} from '../../packages/vehicle-visuals/sculpt.js';
import {MeshoptSimplifier} from '../../vendor/meshoptimizer/7b2d4f4c817aea55d74dcd65d9763ac2ca608026/meshopt_simplifier.module.js';

const root=fileURLToPath(new URL('../../',import.meta.url));
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const bytes=array=>Buffer.from(array.buffer,array.byteOffset,array.byteLength);
const encode=array=>bytes(array).toString('base64');
export function surfaceHash(g){return hash(Buffer.concat(['position','normal','uv'].map(k=>bytes(g.attributes[k].array)).concat(bytes(g.index.array))));}
await MeshoptSimplifier.ready;
const output={},report={schema:1,method:'meshoptimizer edge-collapse; retained author vertices and attributes',
  simplifier:{repository:'https://github.com/zeux/meshoptimizer',commit:'7b2d4f4c817aea55d74dcd65d9763ac2ca608026',release:'v0.24',license:'MIT'},
  sculptSha256:hash(fs.readFileSync(path.join(root,'packages/vehicle-visuals/sculpt.js'))),bodies:[]};
for(const body of VEHICLE_BODIES){
  const parts=sculptRoadVehicle(T,body.id),sourceCount=[...parts.values()].reduce((n,g)=>n+g.index.count/3,0);
  const row={id:body.id,sourceTriangles:sourceCount,triangles:0,parts:[]};output[body.id]={};
  for(const [name,g]of parts){
    const p=g.attributes.position.array,input=new Uint32Array(g.index.array);
    const target=Math.floor(11200*g.index.count/(sourceCount*3))*3;
    const [indices,errorM]=MeshoptSimplifier.simplify(input,p,3,target,.008,['ErrorAbsolute']);
    const remap=new Map(),compact=[];for(const i of indices){if(!remap.has(i))remap.set(i,remap.size);compact.push(remap.get(i));}
    const result={};
    for(const [key,size]of [['position',3],['normal',3],['uv',2]]){
      const source=g.attributes[key].array,array=new Float32Array(remap.size*size);
      for(const [old,i]of remap)for(let c=0;c<size;c++)array[i*size+c]=source[old*size+c];
      result[key]=encode(array);
    }
    result.index=encode(new Uint16Array(compact));output[body.id][name]=result;
    row.triangles+=indices.length/3;
    row.parts.push({name,sourceTriangles:g.index.count/3,triangles:indices.length/3,errorM,
      sourceSurfaceSha256:surfaceHash(g),reducedIndexSha256:hash(bytes(indices)),vertices:remap.size});g.dispose();
  }
  if(sourceCount<30000||row.triangles<10000||row.triangles>14000)throw Error('Vehicle reduction outside author/game budget: '+JSON.stringify(row));
  report.bodies.push(row);console.log(body.id+': '+sourceCount+' -> '+row.triangles+' triangles');
}
const data='// Generated by tools/vehicle-art/bake.mjs. Float32 attributes; Uint16 indices; little-endian.\nexport const VEHICLE_MESH_DATA = '+JSON.stringify(output)+';\n';
fs.writeFileSync(path.join(root,'packages/vehicle-visuals/reduced-data.js'),data);
report.reducedDataSha256=hash(Buffer.from(data));
fs.writeFileSync(path.join(root,'packages/vehicle-visuals/reduction.json'),JSON.stringify(report,null,2)+'\n');
