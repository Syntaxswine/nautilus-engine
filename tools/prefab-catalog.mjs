import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import * as T from '../vendor/aft/781246a668c723d5a4c5463e70534cc04b6a5641/dist/tactics/vendor/three.module.js';
import {createGrossHouse} from '../vendor/tinderbox-prefabs/6693bfa3fea2edec77649d830de5ac68ba4c1a50/src/art/gross-housing.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export function prefabCatalogueSource() {
  const source = JSON.parse(fs.readFileSync(path.join(root,'upstream.json'))).tinderboxPrefabs;
  const catalogue = JSON.parse(fs.readFileSync(path.join(root,source.root,'assets/art/gross-housing-v1/houses.json')));
  const assets = catalogue.houses.map(house => {
    const model = createGrossHouse(T,{catalogue,textures:{}},house.id);
    try {
      const bounds = new T.Box3().setFromObject(model.root);
      const number = n => Math.round(n * 1e6) / 1e6;
      return {id:house.id,name:house.label,collection:'Gross catalogue · c.1891',
        bounds:[bounds.min.x,bounds.min.z,bounds.max.x,bounds.max.z].map(number),
        height:number(bounds.max.y-bounds.min.y),width:house.width,depth:house.depth,
        levels:model.levels,entry:house.floors[0].entry,source:house.source,
        plate:'art/source/gross-housing-v1/plates/n'+house.source.leaf+'.jpg',
        plan:'assets/art/gross-housing-v1/prefabs/'+house.id+'.json',
        partyWalls:!!house.partyWalls,stats:model.diagnostics()};
    } finally {model.dispose();}
  });
  return '// Generated by node tools/prefab-catalog.mjs --write; checked against native geometry.\n'+
    'export const PREFAB_SOURCE_ROOT = '+JSON.stringify(source.root)+';\n'+
    'export const PREFAB_CATALOGUE = '+JSON.stringify('tinderbox-gross-housing-v1@'+source.commit)+';\n'+
    'const freeze = value => {if(value && typeof value === "object"){Object.values(value).forEach(freeze);Object.freeze(value);}return value;};\n'+
    'export const BUILDING_ASSETS = freeze('+JSON.stringify(assets,null,2)+');\n';
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const file = path.join(root,'packages/prefab-core/catalogue.js'), expected = prefabCatalogueSource();
  if (process.argv.includes('--write')) {fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,expected);}
  else if (fs.readFileSync(file,'utf8') !== expected) throw Error('Prefab catalogue differs from its pinned native geometry. Regenerate deliberately.');
  console.log('Verified 13 native house bounds, source bindings and floor inventories.');
}
